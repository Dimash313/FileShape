"""Offline prototype of an atomic SQLite dispatch outbox for FileShape 5.0.

NOT production wiring. The existing API still runs in one process and
JobRuntime's restart policy fails interrupted jobs. This subclass is for
contract tests and migration design: it must not be used by JobRuntime or
network workers until trusted artifact staging, restart recovery, output
fencing and scheduler authentication are implemented.

Only the *trusted server* may call these methods. An opaque artifact ID or
lease is never user authorization, and a lease is not an output publish grant.
"""
from __future__ import annotations

from contextlib import contextmanager
from dataclasses import dataclass
import hashlib
import hmac
import math
import secrets
import time

from api.durable_jobs import (
    DurableJobStore, IdempotencyConflict, IdempotencyPending, serialized,
)
from api.job_envelope import SingleFileJobV1
from api.jobs import JobNotFound, JobStateError

MAX_DELIVERIES = 3


class DispatchLeaseConflict(Exception):
    """Lease expired, was superseded, or was cancelled."""


@dataclass(frozen=True, slots=True)
class DispatchLease:
    envelope: SingleFileJobV1
    token: str
    attempt: int
    expires_at: float


def _now(value: float | None) -> float:
    if value is None:
        value = time.time()
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError("Invalid time")
    if not math.isfinite(value) or value <= 0 or value > 253402300799:
        raise ValueError("Invalid time")
    return float(value)


def _lease_seconds(value: int) -> int:
    if type(value) is not int or not 1 <= value <= 120:
        raise ValueError("Invalid lease duration")
    return value


def _token_hash(token: str) -> str:
    if type(token) is not str or len(token) != 32 or not token.isascii():
        raise DispatchLeaseConflict()
    return hashlib.sha256(token.encode("ascii")).hexdigest()


class DurableDispatchStore(DurableJobStore):
    """Separate opt-in adapter; never instantiated by the current API runtime.

    Atomic admission binds quota, the job record, hashed request idempotency
    and the path-free envelope to one SQLite transaction. It assumes a
    trusted caller has *already verified and staged* the input artifact.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        try:
            self._db.execute("""
                CREATE TABLE IF NOT EXISTS dispatch_outbox (
                    job_id TEXT PRIMARY KEY REFERENCES jobs(job_id) ON DELETE CASCADE,
                    envelope BLOB NOT NULL CHECK(length(envelope) <= 2048),
                    state TEXT NOT NULL CHECK(
                        state IN ('queued','leased','completed','failed','cancelled')
                    ),
                    attempts INTEGER NOT NULL DEFAULT 0
                        CHECK(attempts >= 0 AND attempts <= 3),
                    lease_hash TEXT,
                    lease_until REAL,
                    created_at REAL NOT NULL,
                    updated_at REAL NOT NULL,
                    CHECK(
                        (state = 'leased' AND lease_hash IS NOT NULL AND lease_until IS NOT NULL)
                        OR
                        (state <> 'leased' AND lease_hash IS NULL AND lease_until IS NULL)
                    )
                )
            """)
            self._db.execute("""
                CREATE INDEX IF NOT EXISTS idx_dispatch_ready
                ON dispatch_outbox(state, lease_until, created_at)
            """)
        except BaseException:
            self.close()
            raise

    @contextmanager
    def _transaction(self):
        """Caller already holds inherited RLock; all mutations are serialized."""
        self._db.execute("BEGIN IMMEDIATE")
        try:
            yield
            self._db.execute("COMMIT")
        except BaseException:
            self._db.execute("ROLLBACK")
            raise

    @serialized
    def admit_staged_single(
        self, owner_id: int, key_hash: str, fingerprint: str,
        *, input_ref: str, result_ref: str, action: str, suffix: str,
        pages: str = "", now: float | None = None,
    ) -> tuple[SingleFileJobV1, bool]:
        """Atomically commit an *already staged and verified* single-file job.

        Both hashes must be generated by trusted server code. The caller must
        delete abandoned artifacts on rejected admission; this adapter does
        not own file bytes and must not resolve input_ref as a pathname.
        """
        self._validate_owner(owner_id)
        self._validate_admission_hash(key_hash)
        self._validate_admission_hash(fingerprint)
        timestamp = _now(now)
        with self._transaction():
            existing = self._db.execute(
                """SELECT a.fingerprint,a.accepted,d.envelope
                   FROM admissions AS a
                   JOIN dispatch_outbox AS d ON d.job_id=a.job_id
                   JOIN jobs AS j ON j.job_id=a.job_id
                   WHERE a.owner_id=? AND a.key_hash=? AND j.owner_id=?""",
                (owner_id, key_hash, owner_id),
            ).fetchone()
            if existing is not None:
                if existing[0] != fingerprint:
                    raise IdempotencyConflict()
                if not existing[1]:
                    raise IdempotencyPending()
                return SingleFileJobV1.from_json(existing[2]), False

            # A previously reserved admission without its outbox must never
            # be replaced or billed again under the same key.
            if self._db.execute(
                "SELECT 1 FROM admissions WHERE owner_id=? AND key_hash=?",
                (owner_id, key_hash),
            ).fetchone():
                raise IdempotencyPending()

            # This reserves quota in the SAME transaction as dispatch creation.
            job = self._insert_queued(owner_id, timestamp, metered=True)
            envelope = SingleFileJobV1(
                job_id=job.job_id, input_ref=input_ref, result_ref=result_ref,
                action=action, suffix=suffix, pages=pages,
            )
            payload = envelope.to_json()
            self._db.execute(
                """INSERT INTO admissions
                   (owner_id,key_hash,fingerprint,job_id,accepted,created_at)
                   VALUES(?,?,?,?,1,?)""",
                (owner_id, key_hash, fingerprint, job.job_id, timestamp),
            )
            self._db.execute(
                """INSERT INTO dispatch_outbox
                   (job_id,envelope,state,created_at,updated_at)
                   VALUES(?,?,'queued',?,?)""",
                (job.job_id, payload, timestamp, timestamp),
            )
            return envelope, True

    @serialized
    def expire_exhausted(self, *, now: float | None = None, limit: int = 100) -> int:
        """Mark exhausted expired leases failed and release reserved quota."""
        timestamp = _now(now)
        if type(limit) is not int or not 1 <= limit <= 100:
            raise ValueError("Invalid reconciliation batch")
        with self._transaction():
            expired = self._db.execute(
                """SELECT d.job_id,j.owner_id FROM dispatch_outbox AS d
                   JOIN jobs AS j ON j.job_id=d.job_id
                   WHERE d.state='leased' AND d.attempts>=?
                     AND d.lease_until<=?
                   ORDER BY d.lease_until,d.job_id LIMIT ?""",
                (MAX_DELIVERIES, timestamp, limit),
            ).fetchall()
            for job_id, owner_id in expired:
                changed = self._db.execute(
                    """UPDATE jobs SET state='failed',updated_at=?
                       WHERE job_id=? AND owner_id=? AND state='processing'""",
                    (timestamp, job_id, owner_id),
                ).rowcount
                if changed != 1:
                    raise JobStateError()
                self._settle_job_operation_in_transaction(
                    job_id, owner_id, success=False, now=timestamp,
                )
                self._db.execute(
                    """UPDATE dispatch_outbox
                       SET state='failed',lease_hash=NULL,lease_until=NULL,updated_at=?
                       WHERE job_id=?""",
                    (timestamp, job_id),
                )
            return len(expired)

    @serialized
    def claim_next(
        self, *, now: float | None = None, lease_seconds: int = 60,
    ) -> DispatchLease | None:
        """Claim or re-claim once, invalidating any older lease token."""
        timestamp = _now(now)
        seconds = _lease_seconds(lease_seconds)
        # Keep expired reservations from remaining charged indefinitely.
        self.expire_exhausted(now=timestamp)
        with self._transaction():
            row = self._db.execute(
                """SELECT d.job_id,d.envelope,d.state,d.attempts,j.state
                   FROM dispatch_outbox AS d
                   JOIN jobs AS j ON j.job_id=d.job_id
                   WHERE d.state='queued'
                     OR (d.state='leased' AND d.lease_until<=?
                         AND d.attempts<?)
                   ORDER BY d.created_at,d.job_id LIMIT 1""",
                (timestamp, MAX_DELIVERIES),
            ).fetchone()
            if row is None:
                return None
            job_id, payload, state, attempts, job_state = row
            if (state == "queued" and job_state != "queued") or (
                state == "leased" and job_state != "processing"
            ):
                raise JobStateError()
            envelope = SingleFileJobV1.from_json(payload)
            if envelope.job_id != job_id:
                raise JobStateError()
            if state == "queued":
                changed = self._db.execute(
                    """UPDATE jobs SET state='processing',updated_at=?
                       WHERE job_id=? AND state='queued'""",
                    (timestamp, job_id),
                ).rowcount
                if changed != 1:
                    raise JobStateError()
            token = secrets.token_urlsafe(24)
            expiry = timestamp + seconds
            updated = self._db.execute(
                """UPDATE dispatch_outbox
                   SET state='leased',attempts=attempts+1,
                       lease_hash=?,lease_until=?,updated_at=?
                   WHERE job_id=? AND state=?""",
                (hashlib.sha256(token.encode("ascii")).hexdigest(),
                 expiry, timestamp, job_id, state),
            ).rowcount
            if updated != 1:
                raise DispatchLeaseConflict()
            return DispatchLease(envelope, token, attempts + 1, expiry)

    def _require_current_lease(
        self, job_id: str, owner_id: int, token: str, now: float,
    ) -> float:
        row = self._db.execute(
            """SELECT j.owner_id,d.state,d.lease_hash,d.lease_until
               FROM dispatch_outbox AS d JOIN jobs AS j ON j.job_id=d.job_id
               WHERE d.job_id=?""", (job_id,),
        ).fetchone()
        if row is None or row[0] != owner_id:
            raise JobNotFound()
        if row[1] != "leased" or row[2] is None or row[3] <= now or (
            not hmac.compare_digest(row[2], _token_hash(token))
        ):
            raise DispatchLeaseConflict()
        return float(row[3])

    @serialized
    def renew_lease(
        self, job_id: str, owner_id: int, token: str,
        *, now: float | None = None, lease_seconds: int = 60,
    ) -> float:
        """Extend only the current unexpired owner-scoped lease."""
        self._validate_owner(owner_id)
        timestamp = _now(now)
        seconds = _lease_seconds(lease_seconds)
        with self._transaction():
            prior_expiry = self._require_current_lease(job_id, owner_id, token, timestamp)
            expiry = max(prior_expiry, timestamp + seconds)
            self._db.execute(
                "UPDATE dispatch_outbox SET lease_until=?,updated_at=? WHERE job_id=?",
                (expiry, timestamp, job_id),
            )
            return expiry

    @serialized
    def settle_lease(
        self, job_id: str, owner_id: int, token: str, *, success: bool,
        now: float | None = None,
    ) -> bool:
        """Settle job state, quota and outbox atomically; reject stale ACKs.

        A successful result must already have been durably verified and
        authorized by the future artifact service, NOT just by the worker.
        """
        self._validate_owner(owner_id)
        if type(success) is not bool:
            raise ValueError("Invalid settlement")
        timestamp = _now(now)
        with self._transaction():
            self._require_current_lease(job_id, owner_id, token, timestamp)
            state = "completed" if success else "failed"
            updated = self._db.execute(
                """UPDATE jobs SET state=?,updated_at=?
                   WHERE job_id=? AND owner_id=? AND state='processing'""",
                (state, timestamp, job_id, owner_id),
            ).rowcount
            if updated != 1:
                raise JobStateError()
            self._settle_job_operation_in_transaction(
                job_id, owner_id, success=success, now=timestamp,
            )
            self._db.execute(
                """UPDATE dispatch_outbox
                   SET state=?,lease_hash=NULL,lease_until=NULL,updated_at=?
                   WHERE job_id=?""",
                (state, timestamp, job_id),
            )
            return True

    @serialized
    def cancel_dispatch(
        self, job_id: str, owner_id: int, *, now: float | None = None,
    ) -> bool:
        """Owner-only cancellation invalidates outstanding leases and refunds."""
        self._validate_owner(owner_id)
        timestamp = _now(now)
        with self._transaction():
            row = self._db.execute(
                """SELECT j.owner_id,j.state,d.state
                   FROM dispatch_outbox AS d JOIN jobs AS j ON j.job_id=d.job_id
                   WHERE d.job_id=?""", (job_id,),
            ).fetchone()
            if row is None or row[0] != owner_id:
                raise JobNotFound()
            if row[2] in {"completed", "failed", "cancelled"}:
                return False
            if row[1] not in {"queued", "processing"}:
                raise JobStateError()
            changed = self._db.execute(
                """UPDATE jobs SET state='cancelled',updated_at=?
                   WHERE job_id=? AND owner_id=? AND state=?""",
                (timestamp, job_id, owner_id, row[1]),
            ).rowcount
            if changed != 1:
                raise JobStateError()
            self._settle_job_operation_in_transaction(
                job_id, owner_id, success=False, now=timestamp,
            )
            self._db.execute(
                """UPDATE dispatch_outbox
                   SET state='cancelled',lease_hash=NULL,lease_until=NULL,updated_at=?
                   WHERE job_id=?""",
                (timestamp, job_id),
            )
            return True
